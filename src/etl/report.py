"""Report rendering utilities for the ETL pipeline.

The pipeline returns a dict with metrics and validation results.  This module
converts that information into a concise Markdown report that can be saved to
``reports/``.
"""

from typing import Dict, Any


def render_report(
    run_id: str,
    run_timestamp: str,
    status: str,
    metrics: Dict[str, Any],
    validation_report: Dict[str, Any],
) -> str:
    """Build a markdown report string.

    Args:
        run_id: UUID of the ETL execution.
        run_timestamp: ISO‑8601 timestamp.
        status: ``SUCCESS`` or ``FAILED``.
        metrics: Dictionary of per‑table row counts etc. (generated by
            ``src.etl.metrics.compute_metrics``).
        validation_report: Full validation JSON produced by ``DataValidator``.
    Returns:
        A markdown‑formatted string.
    """
    lines = []
    lines.append("# ETL Run Report")
    lines.append(f"**Run ID:** `{run_id}`")
    lines.append(f"**Timestamp (UTC):** {run_timestamp}")
    lines.append(f"**Overall Status:** {status}\n")

    lines.append("## Table Row Metrics")
    lines.append("| Table | Rows |")
    lines.append("|---|---|")
    for tbl, cnt in metrics.get("row_counts", {}).items():
        lines.append(f"| {tbl} | {cnt} |")
    lines.append("")

    lines.append("## Validation Summary")
    summary = validation_report.get("summary", {})
    lines.append(f"* Total checks: {summary.get('total_checks', 0)}")
    lines.append(f"* Passed: {summary.get('passed_checks', 0)}")
    lines.append(f"* Failed: {summary.get('failed_checks', 0)}")
    lines.append(f"* Pass rate: {summary.get('pass_rate_pct', 0)}%\n")

    if summary.get("failed_checks", 0) > 0:
        lines.append("### Failed Checks Details")
        for check in validation_report.get("detailed_results", []):
            if check.get("status") == "FAILED":
                lines.append(
                    f"* **{check.get('table')}** – {check.get('check_name')}: {check.get('details')}"
                )
        lines.append("")

    lines.append("---")
    lines.append("*(Generated automatically by the ETL pipeline)*")
    return "\n".join(lines)
